<?php

session_start();

/*
|--------------------------------------------------------------------------
| LIMPA A SESSÃO
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| REMOVE O COOKIE DA SESSÃO
|--------------------------------------------------------------------------
*/

if (ini_get("session.use_cookies")) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        "",
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );

}


/*
|--------------------------------------------------------------------------
| DESTROI A SESSÃO
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| VOLTA PARA O LOGIN
|--------------------------------------------------------------------------
*/

header("Location: login.php");
exit;