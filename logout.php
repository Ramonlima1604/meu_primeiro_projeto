<?php

/*
|--------------------------------------------------------------------------
| INICIAR SESSÃO
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| LIMPAR DADOS DA SESSÃO
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| REMOVER COOKIE DA SESSÃO
|--------------------------------------------------------------------------
*/

if (ini_get("session.use_cookies")) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        "",
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}


/*
|--------------------------------------------------------------------------
| DESTRUIR SESSÃO
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| VOLTAR PARA A TELA PRINCIPAL
|--------------------------------------------------------------------------
*/

header(
    "Location: /sistema_bolos/index.php"
);

exit;